package io.github.logdelta.core.report;

import io.github.logdelta.core.Version;
import io.github.logdelta.core.analysis.FlakyLine;
import io.github.logdelta.core.analysis.FrequencyShift;
import io.github.logdelta.core.analysis.InsightItem;
import io.github.logdelta.core.analysis.Insights;
import io.github.logdelta.core.analysis.ProblemTimeline;
import io.github.logdelta.core.analysis.TemplateShift;
import io.github.logdelta.core.engine.DiffResult;
import io.github.logdelta.core.io.LogFile;
import io.github.logdelta.core.model.DiffRow;
import io.github.logdelta.core.model.DiffStats;
import io.github.logdelta.core.model.Hunk;
import io.github.logdelta.core.structured.StructuredLines;
import io.github.logdelta.core.suggest.RuleSuggestion;
import io.github.logdelta.core.timing.PhaseChange;
import io.github.logdelta.core.timing.Timeline;
import io.github.logdelta.core.timing.TimingAnalysis;
import io.github.logdelta.core.util.LogText;
import io.github.logdelta.core.util.Text;

import java.io.IOException;
import java.util.List;
import java.util.Locale;

/// Writes a compact Markdown summary meant for pull requests, tickets and chat.
///
/// Sections: overview table, new and resolved problems, frequency shifts, and the first
/// hunks as `diff` code blocks. Code blocks are limited to 10 hunks unless
/// [ReportOptions#maxHunks()] says otherwise, to keep the result pasteable.
public final class MarkdownReportWriter implements ReportWriter {

    private static final int DEFAULT_MAX_HUNKS = 10;
    private static final int MAX_ITEMS = 25;
    private static final int MAX_TEXT = 160;

    @Override
    public void write(DiffResult r, ReportOptions options, Appendable out) throws IOException {
        DiffStats s = r.stats();
        Insights in = r.insights();
        out.append("# Log comparison\n\n");
        out.append("**Baseline:** ").append(file(r.leftFile())).append("  \n");
        out.append("**Candidate:** ").append(file(r.rightFile())).append("\n\n");
        if (!r.extraBaselines().isEmpty()) {
            out.append("Also compared with ").append(String.valueOf(r.extraBaselines().size()))
                    .append(" more baseline run(s); ").append(String.valueOf(s.expected()))
                    .append(" difference(s) they explain are treated as normal variation.\n\n");
        }

        String detected = r.detection().describe();
        if (!detected.isEmpty()) {
            out.append("**Format:** ").append(detected).append("  \n");
        }
        if (r.options().timeWindow() != null) {
            out.append("**Time window:** ").append(r.options().timeWindow().describe()).append("  \n");
        }
        if (!detected.isEmpty() || r.options().timeWindow() != null) {
            out.append('\n');
        }

        if (s.identical()) {
            out.append("> The logs are identical after normalization.\n");
            return;
        }

        out.append("| Similarity | Modified | Removed | Added | Moved | New problems |\n");
        out.append("|---:|---:|---:|---:|---:|---:|\n");
        out.append(String.format(Locale.ROOT, "| %.1f%% | %d | %d | %d | %d | %d |%n%n", s.similarity() * 100,
                s.modified(), s.removed() - s.moved(), s.added() - s.moved(), s.moved(), in.newProblems().size()));

        if (in.firstDivergenceRow() >= 0) {
            DiffRow row = r.rows().get(in.firstDivergenceRow());
            out.append("**First divergence:** ");
            out.append(row.hasLeft() ? "baseline line " + r.left(row).number() : "baseline end");
            out.append(" / ");
            out.append(row.hasRight() ? "candidate line " + r.right(row).number() : "candidate end");
            out.append("\n\n");
        }

        timeline(out, r.problemTimeline());
        problems(out, "New problems", "candidate", in.newProblems());
        problems(out, "Resolved problems", "baseline", in.resolvedProblems());
        shifts(out, in.frequencyShifts());
        templates(out, in.templateShifts());
        timing(out, r);
        flaky(out, in.flakyLines());
        suggestions(out, r);
        hunks(out, r, options);
        out.append("\n<sub>Generated by ").append(Version.displayName());
        if (r.redactedSecrets() > 0) {
            out.append(" \u00b7 ").append(String.valueOf(r.redactedSecrets())).append(" secret(s) redacted");
        }
        out.append("</sub>\n");
    }

    private static String file(LogFile f) {
        return "`" + f.displayName().replace("`", "'") + "` (" + String.format(Locale.ROOT, "%,d", f.lineCount())
                + " lines, " + Text.humanBytes(f.sizeBytes()) + ")";
    }

    private static void problems(Appendable out, String title, String side, List<InsightItem> items)
            throws IOException {
        if (items.isEmpty()) {
            return;
        }
        out.append("## ").append(title).append(" (").append(String.valueOf(items.size())).append(")\n\n");
        out.append("| ").append(side.substring(0, 1).toUpperCase(Locale.ROOT)).append(side.substring(1))
                .append(" line | Severity | Message |\n|---:|:---|:---|\n");
        int n = 0;
        for (InsightItem i : items) {
            if (n++ >= MAX_ITEMS) {
                out.append("| | | _").append(String.valueOf(items.size() - MAX_ITEMS)).append(" more..._ |\n");
                break;
            }
            String extra = i.lines() > 1 ? " _(+" + (i.lines() - 1) + " lines)_" : "";
            if (i.repeated()) {
                extra += " **\u00d7" + i.occurrences() + "** " + code(i.template());
            }
            out.append("| ").append(String.valueOf(i.lineNumber())).append(" | ").append(i.severity().label())
                    .append(" | ").append(code(i.text())).append(extra).append(" |\n");
        }
        out.append('\n');
    }

    private static void shifts(Appendable out, List<FrequencyShift> shifts) throws IOException {
        if (shifts.isEmpty()) {
            return;
        }
        out.append("## Frequency shifts\n\nMessages whose number of occurrences changed notably.\n\n");
        out.append("| Message | Baseline | Candidate | Change |\n|:---|---:|---:|---:|\n");
        for (FrequencyShift f : shifts) {
            out.append("| ").append(code(f.template())).append(" | ").append(String.valueOf(f.leftCount()))
                    .append(" | ").append(String.valueOf(f.rightCount())).append(" | ")
                    .append(f.delta() > 0 ? "+" : "").append(String.valueOf(f.delta())).append(" |\n");
        }
        out.append('\n');
    }

    private static void timeline(Appendable out, ProblemTimeline t) throws IOException {
        if (t == null || !t.hasProblems()) {
            return;
        }
        out.append("## Warnings and errors ").append(t.byTime() ? "over " + Timeline.format(t.spanMillis())
                : "through the file").append("\n\n```text\n");
        int peak = Math.max(1, t.peak());
        out.append("baseline  ").append(spark(t.left(), peak)).append(String.format(Locale.ROOT,
                "  %d errors, %d warnings%n", t.left().totalErrors(), t.left().totalWarnings()));
        out.append("candidate ").append(spark(t.right(), peak)).append(String.format(Locale.ROOT,
                "  %d errors, %d warnings%n", t.right().totalErrors(), t.right().totalWarnings()));
        out.append("```\n\n");
    }

    /// A sparkline of one side's problem counts.
    static String spark(ProblemTimeline.Side side, int peak) {
        String chars = " \u2581\u2582\u2583\u2584\u2585\u2586\u2587\u2588";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < side.warnings().length; i++) {
            int n = side.warnings()[i] + side.errors()[i];
            int level = n == 0 ? 0 : Math.max(1, (int) Math.round(n * 8.0 / peak));
            sb.append(chars.charAt(level));
        }
        return sb.toString();
    }

    private static void templates(Appendable out, List<TemplateShift> shifts) throws IOException {
        if (shifts.isEmpty()) {
            return;
        }
        out.append("## Message templates\n\nKinds of message whose number changed notably; `<*>` is a part that varies.\n\n");
        out.append("| Template | Baseline | Candidate | Change |\n|:---|---:|---:|---:|\n");
        for (TemplateShift t : shifts) {
            out.append("| ").append(code(t.template())).append(" | ").append(String.valueOf(t.leftCount()))
                    .append(" | ").append(String.valueOf(t.rightCount())).append(" | ")
                    .append(t.delta() > 0 ? "+" : "").append(String.valueOf(t.delta())).append(" |\n");
        }
        out.append('\n');
    }

    private static void flaky(Appendable out, List<FlakyLine> lines) throws IOException {
        if (lines.isEmpty()) {
            return;
        }
        out.append("## Flaky lines\n\nBaseline lines that differ between the good runs themselves:\n\n");
        for (FlakyLine f : lines) {
            out.append("- line ").append(String.valueOf(f.lineNumber())).append(": ").append(code(f.text()))
                    .append(" \u2014 ").append(f.kind().description());
            if (f.similarLines() > 0) {
                out.append(" (+").append(String.valueOf(f.similarLines())).append(" similar)");
            }
            if (!f.rules().isEmpty()) {
                out.append("; mask with ``");
                for (int k = 0; k < f.rules().size(); k++) {
                    out.append(k == 0 ? "" : " ").append("--mask '").append(shellQuoted(f.rules().get(k).regex()
                            + "=>" + f.rules().get(k).replacement())).append("'");
                }
                out.append("``");
            } else if (f.ignorePattern() != null) {
                out.append("; ignore with ``-I '").append(shellQuoted(f.ignorePattern())).append("'``");
            }
            out.append('\n');
        }
        out.append('\n');
    }

    private static void timing(Appendable out, DiffResult r) throws IOException {
        TimingAnalysis t = r.timing();
        if (!t.available() || t.slower().isEmpty() && t.faster().isEmpty()) {
            return;
        }
        out.append("## Timing\n\nRun duration: ").append(Timeline.format(t.left().duration())).append(" \u2192 ")
                .append(Timeline.format(t.right().duration())).append("\n\n");
        out.append("| Phase (from \u2192 to) | Baseline | Candidate | Change |\n|:---|---:|---:|---:|\n");
        List<PhaseChange> all = new java.util.ArrayList<>(t.slower());
        all.addAll(t.faster());
        for (PhaseChange p : all) {
            out.append("| ").append(code(LogText.message(p.startText()))).append(" \u2192 ")
                    .append(code(LogText.message(p.endText()))).append(" | ").append(Timeline.format(p.leftMillis()))
                    .append(" | ").append(Timeline.format(p.rightMillis())).append(" | ")
                    .append(p.delta() > 0 ? "+" : "").append(Timeline.format(p.delta())).append(" |\n");
        }
        out.append('\n');
    }

    private static void suggestions(Appendable out, DiffResult r) throws IOException {
        if (r.suggestions().isEmpty()) {
            return;
        }
        out.append("## Suggested rules\n\nThese rules would hide differences that look run-specific:\n\n");
        for (RuleSuggestion s : r.suggestions()) {
            out.append("- ").append(String.valueOf(s.resolves())).append(" modified lines ").append(s.summary())
                    .append(": ``--mask '").append(shellQuoted(s.rule().regex() + "=>" + s.rule().replacement()))
                    .append("'``\n");
        }
        out.append('\n');
    }

    private static void hunks(Appendable out, DiffResult r, ReportOptions options) throws IOException {
        List<Hunk> hunks = r.hunks(options.contextLines());
        int max = options.maxHunks() > 0 ? options.maxHunks() : DEFAULT_MAX_HUNKS;
        out.append("## Changes\n\n");
        int shown = Math.min(max, hunks.size());
        for (int h = 0; h < shown; h++) {
            Hunk hunk = hunks.get(h);
            out.append("```diff\n");
            for (int i = hunk.startRow(); i < hunk.endRow(); i++) {
                DiffRow row = r.rows().get(i);
                switch (row.kind()) {
                    case UNCHANGED -> out.append("  ").append(r.left(row).text()).append('\n');
                    case REMOVED -> out.append("- ").append(r.left(row).text()).append('\n');
                    case ADDED -> out.append("+ ").append(r.right(row).text()).append('\n');
                    case MODIFIED -> {
                        out.append("- ").append(r.left(row).text()).append('\n')
                                .append("+ ").append(r.right(row).text()).append('\n');
                        List<StructuredLines.FieldChange> changes = r.fieldChanges(row);
                        if (!changes.isEmpty()) {
                            out.append("@@ ");
                            for (int c = 0; c < changes.size(); c++) {
                                out.append(c == 0 ? "" : "; ").append(changes.get(c).describe());
                            }
                            out.append(" @@\n");
                        }
                    }
                    default -> throw new IllegalStateException();
                }
            }
            out.append("```\n\n");
        }
        if (hunks.size() > shown) {
            out.append("_").append(String.valueOf(hunks.size() - shown))
                    .append(" more change block(s) not shown. Export an HTML report for the full comparison._\n");
        }
    }

    /// Text for inside single quotes in a POSIX shell: `'` becomes `'\''`.
    private static String shellQuoted(String s) {
        return s.replace("'", "'\\''");
    }

    private static String code(String s) {
        String t = Text.truncate(s.strip(), MAX_TEXT).replace("|", "\\|");
        return t.isEmpty() ? "" : "`" + t.replace("`", "'") + "`";
    }
}
