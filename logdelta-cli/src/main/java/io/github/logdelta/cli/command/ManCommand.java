package io.github.logdelta.cli.command;

import io.github.logdelta.cli.CliContext;
import io.github.logdelta.cli.ExitCode;
import io.github.logdelta.cli.args.ArgParser;
import io.github.logdelta.cli.args.OptionSpec;
import io.github.logdelta.cli.args.ParsedArgs;
import io.github.logdelta.core.Version;

import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import java.util.function.Supplier;

/// `logdelta manpage`: prints the manual page in roff format (`man ./logdelta.1` to view it).
///
/// Like the completion scripts, the page is generated from the commands' option declarations
/// and help texts, so it always matches the program.
public final class ManCommand implements Command {

    private final Supplier<List<Command>> commands;

    /// @param commands every command of the CLI, including this one
    public ManCommand(Supplier<List<Command>> commands) {
        this.commands = commands;
    }

    @Override
    public String name() {
        return "manpage";
    }

    @Override
    public String summary() {
        return "print the manual page (roff); view it with 'man ./logdelta.1'";
    }

    @Override
    public String usage() {
        return "manpage [--date YYYY-MM-DD] > logdelta.1";
    }

    @Override
    public ArgParser parser() {
        return new ArgParser()
                .add(OptionSpec.value("date", '\0', "DATE", "date printed in the footer (default: today)"))
                .add(OptionSpec.flag("help", 'h', "show this help"));
    }

    @Override
    public int execute(ParsedArgs args, CliContext ctx) {
        String date = args.get("date", LocalDate.now().format(DateTimeFormatter.ISO_LOCAL_DATE));
        ctx.out().print(render(date));
        ctx.out().flush();
        return ExitCode.OK;
    }

    /// The manual page.
    String render(String date) {
        StringBuilder sb = new StringBuilder();
        sb.append(".\\\" Generated by 'logdelta manpage'. Do not edit; change the command help instead.\n");
        sb.append(".TH LOGDELTA 1 \"").append(date).append("\" \"").append(esc(Version.displayName()))
                .append("\" \"User Commands\"\n");
        sb.append(".SH NAME\nlogdelta \\- compare log files while ignoring what always changes\n");
        sb.append(".SH SYNOPSIS\n");
        for (Command c : commands.get()) {
            sb.append(".B logdelta\n").append(esc(c.usage())).append("\n.br\n");
        }
        sb.append(".B logdelta gui\n[BASELINE CANDIDATE]\n");
        sb.append(".SH DESCRIPTION\n");
        sb.append("""
                LogDelta masks the parts of log lines that differ on every run (timestamps, request ids,
                thread numbers, memory addresses, durations) and then compares what is left, so the only
                differences shown are the ones that matter. It reports new and resolved warnings and
                errors, messages and message templates whose frequency changed, phases that got slower,
                lines that vary between good runs, and where the runs first diverge.
                .PP
                JSON lines and logfmt logs are detected and compared field by field. Built-in profiles
                (presets) recognise Spring Boot, nginx/Apache access logs, Kubernetes, journald, Android
                logcat and Python logging. Reports have secrets and e-mail addresses removed.
                .PP
                When the first argument is not a command,
                .B diff
                is assumed.
                """);
        sb.append(".SH COMMANDS\n");
        for (Command c : commands.get()) {
            sb.append(".TP\n.B ").append(c.name()).append('\n').append(esc(capitalize(c.summary()))).append(".\n");
        }
        sb.append(".TP\n.B help\nShow the options of a command.\n");
        for (Command c : commands.get()) {
            sb.append(".SH \"").append(c.name().toUpperCase(Locale.ROOT)).append(" OPTIONS\"\n");
            for (OptionSpec o : c.parser().specs()) {
                sb.append(".TP\n");
                if (o.shortName() != 0) {
                    sb.append("\\fB\\-").append(o.shortName()).append("\\fR, ");
                }
                sb.append("\\fB\\-\\-").append(esc(o.longName())).append("\\fR");
                if (o.takesValue()) {
                    sb.append(" \\fI").append(esc(o.argName())).append("\\fR");
                }
                sb.append('\n').append(esc(capitalize(o.help()))).append(o.repeatable() ? " (repeatable)" : "")
                        .append(".\n");
            }
            if (!c.details().isBlank()) {
                sb.append(".PP\n.nf\n");
                for (String line : c.details().stripTrailing().split("\n", -1)) {
                    sb.append(line.isEmpty() ? "" : esc(line)).append('\n');
                }
                sb.append(".fi\n");
            }
        }
        sb.append("""
                .SH EXIT STATUS
                .TP
                .B 0
                No differences (\\fBdiff\\fR) or the check passed (\\fBcheck\\fR).
                .TP
                .B 1
                Differences, new problems with \\fB\\-\\-exit\\-code problems\\fR, or the check failed.
                .TP
                .B 2
                Invalid arguments or an error.
                .SH FILES
                .TP
                .I .logdelta
                A profile in the current folder, or in the nearest parent folder up to the root of the Git
                repository, is loaded automatically unless \\fB\\-\\-profile\\fR or \\fB\\-\\-no\\-profile\\fR is given.
                .TP
                .I *.ldprofile
                Profiles: rules, ignore patterns and options to share between the command line, the desktop
                application and a team.
                .TP
                .I *.ldsession
                Sessions saved by the desktop application: sources, rules, bookmarks and notes.
                .SH ENVIRONMENT
                .TP
                .B NO_COLOR
                Disables colour when set (see https://no\\-color.org).
                .TP
                .B COLUMNS
                Terminal width used for side\\-by\\-side output.
                .TP
                .B LOGDELTA_AUTO_PROFILE
                Set to 0 to never load a \\fI.logdelta\\fR profile automatically.
                .TP
                .B GITHUB_STEP_SUMMARY
                With \\fBcheck \\-\\-github\\fR, the Markdown summary is appended to this file.
                .SH EXAMPLES
                .nf
                logdelta good.log bad.log
                logdelta \\-f summary good.jsonl bad.jsonl
                logdelta \\-\\-since +2m \\-\\-until +5m good.log bad.log
                logdelta \\-f html \\-o report.html good\\-1.log good\\-2.log candidate.log
                logdelta check \\-\\-baseline\\-dir .logdelta\\-baselines \\-\\-update\\-on\\-pass build/app.log
                .fi
                .SH SEE ALSO
                Documentation: https://github.com/Yeongwonhan\\-Jeolmang/logdelta/tree/main/docs
                .SH BUGS
                Report bugs at https://github.com/Yeongwonhan\\-Jeolmang/logdelta/issues
                .SH AUTHOR
                Hana Eun\\-Seo.
                .SH COPYRIGHT
                Copyright (C) 2026 Hana Eun\\-Seo. License GPLv3+: GNU GPL version 3 or later
                <https://gnu.org/licenses/gpl.html>.
                This is free software: you are free to change and redistribute it.
                There is NO WARRANTY, to the extent permitted by law.
                """);
        return sb.toString();
    }

    private static String capitalize(String s) {
        return s.isEmpty() ? s : Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    /// Escapes text for roff: backslashes, hyphens, and leading dots or quotes.
    static String esc(String s) {
        String t = s.replace("\\", "\\e").replace("-", "\\-");
        if (t.startsWith(".") || t.startsWith("'")) {
            t = "\\&" + t;
        }
        return t;
    }
}
